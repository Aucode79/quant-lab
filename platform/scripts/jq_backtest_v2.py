def handle_data(context, data):
    """每日：执行买入 + 卖出"""
    today = context.current_dt.strftime('%Y-%m-%d')
    total_value = context.portfolio.total_value

    # 卖出
    for t in g.trades:
        if t[2] == today and t[0] in context.portfolio.positions:
            order_target_value(t[0], 0)

    # 买入 (当天有新交易)
    buy_today = [t for t in g.trades if t[1] == today]
    for t in buy_today:
        try:
            price = data[t[0]].open if data[t[0]].open else data[t[0]].close
            if price is None or price <= 0:
                continue
            trade_cash = total_value / max(1, len(buy_today))
            shares = int(trade_cash / price / 100) * 100
            if shares >= 100:
                order_target_value(t[0], shares * price)
        except:
            pass

    # 记录净值
    g.daily_values.append({
        'date': today,
        'total': context.portfolio.total_value,
    })

def after_trading_end(context):
    """收盘后记录成交"""
    for t in context.trades:
        if t.executed and t.order_amount < 0:  # 卖出
            g.trade_results.append({
                'code': t.security,
                'price': abs(t.price),
            })

    # 最后一天输出对比
    if context.current_dt.strftime('%Y-%m-%d') < '2024-12-30':
        return

    vals = [r['total'] for r in g.daily_values]
    n = len(vals)
    if n < 2: return

    rets = [(vals[i]-vals[i-1])/vals[i-1] for i in range(1,n)]
    total_return = (vals[-1] - vals[0]) / vals[0]
    annual_return = (1+total_return) ** (252/max(n,1)) - 1
    peak = vals[0]; max_dd = 0
    for v in vals:
        peak = max(peak, v)
        max_dd = max(max_dd, (peak-v)/peak if peak>0 else 0)
    rf_daily = 0.03/252
    exc = [r-rf_daily for r in rets]
